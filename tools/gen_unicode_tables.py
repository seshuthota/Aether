"""Generates src/tokenizer/unicode_tables.rs: code-point ranges of Unicode
general category L (letters: Lu, Ll, Lt, Lm, Lo), i.e. regex `\\p{L}`.

    tools/.venv/bin/python -I tools/gen_unicode_tables.py src/tokenizer/unicode_tables.rs

Rust's standard library has `char::is_numeric` (= `\\p{N}`) and
`char::is_whitespace` (= the White_Space property, `\\s`), but nothing equal
to `\\p{L}`: `char::is_alphabetic` also accepts combining marks and letter
numbers. The table is taken from Python's `unicodedata`.
"""

import sys
import unicodedata


def main():
    ranges = []
    for cp in range(0x110000):
        if unicodedata.category(chr(cp)).startswith("L"):
            if ranges and ranges[-1][1] == cp - 1:
                ranges[-1][1] = cp
            else:
                ranges.append([cp, cp])
    lines = [
        "//! Generated by tools/gen_unicode_tables.py from Python's unicodedata",
        f"//! (Unicode {unicodedata.unidata_version}). Do not edit by hand.",
        "",
        "/// Inclusive code-point ranges of general category L (`\\p{L}`), sorted.",
        "pub const LETTER: &[(u32, u32)] = &[",
    ]
    lines += [f"    (0x{a:04X}, 0x{b:04X})," for a, b in ranges]
    lines += ["];", ""]
    open(sys.argv[1], "w").write("\n".join(lines))
    print(f"{len(ranges)} letter ranges (Unicode {unicodedata.unidata_version})")


if __name__ == "__main__":
    main()
